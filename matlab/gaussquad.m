function [quadpoint,quadweight]=gaussquad(p,a,b)
%%%% referencehttps://pomax.github.io/bezierinfo/legendre-gauss.html
if p<0
    disp('error, p must larger than 0');
    return
end

if p>7
    disp('error, rule for p>7 is not available');
    return
end
if p==0
    quadpoint=0;
    quadweight=2;
elseif p==1
    quadpoint=[-sqrt(1/3),sqrt(1/3)];
    quadweight=[1,1];
elseif p==2;
    quadpoint=[-0.774597, 0,0.774597];
    quadweight=[0.5555, 0.8889,0.5555];

elseif p==3;
    quadpoint=[-0.86113631,-0.33998104,0.33998104,0.86113631];
    quadweight=[0.34785485,0.65214515,0.65214515,0.34785485];
elseif p==4;
    quadpoint=[-0.90617985,-0.53846931, 0.00000000, 0.53846931, 0.90617985];
    quadweight=[0.23692689,0.47862867,0.56888889,0.47862867,0.23692689];    
elseif p==5;
    quadpoint=[-0.93246951,-0.66120939,-0.23861919, 0.23861919, 0.66120939, 0.93246951];
    quadweight=[0.17132449,0.36076157,0.46791393,0.46791393,0.36076157,0.17132449];   
elseif p==6;
    
    quadpoint=[-0.9491079123427585,-0.7415311855993945,-0.4058451513773972,      0,           0.4058451513773972,0.7415311855993945,0.9491079123427585];
    quadweight=[0.1294849661688697,  0.2797053914892766,0.3818300505051189,0.4179591836734694, 0.3818300505051189, 0.2797053914892766,0.1294849661688697];  
elseif p==7;
	
    quadpoint=[-0.9602898564975363,-0.7966664774136267,-0.5255324099163290,-0.1834346424956498,0.1834346424956498,0.5255324099163290,0.7966664774136267,0.9602898564975363];
    quadweight=[0.1012285362903763,0.2223810344533745,0.3137066458778873,0.3626837833783620,0.3626837833783620,0.3137066458778873,0.2223810344533745,0.1012285362903763];    
end   





if nargin ==3 
   bma=(b-a)*.5;
   bpa=(b+a)*.5;
   quadpoint=bma*quadpoint+bpa;
   quadweight=quadweight*bma;
   quadpoint=quadpoint';
end